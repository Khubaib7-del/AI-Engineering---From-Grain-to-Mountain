// Map list: hover a module row, expand it, and hover Back on a unit page.
import { chromium } from 'playwright-core';
import fs from 'node:fs';
const base = process.env.PREVIEW_URL ?? 'http://127.0.0.1:8090';
const out = 'design/shots/chat';
fs.mkdirSync(out, { recursive: true });
const browser = await chromium.launch({ executablePath: '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] });
const day = n => { const d = new Date(); d.setDate(d.getDate() - n); return d.toISOString(); };
const seeded = theme => ({ version: 1, lessons: {}, topics: {}, verified: {}, settings: { theme, reminders: false, times: ['09:00'], weekdays: [0, 1, 2, 3, 4, 5, 6], quietStart: '22:00', quietEnd: '08:00' }, profile: { track: 'ai-engineer', level: 'some-python', hoursPerWeek: 8, testedOut: [], startedAt: day(10), onboarded: true }, units: {}, activity: [] });
const errors = [];
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 } });
const page = await ctx.newPage();
page.on('pageerror', e => errors.push(e.message));
await page.addInitScript(s => { localStorage.setItem('ai-learning-v1', JSON.stringify(s)); }, seeded('terminal'));
await page.goto(base + '/map', { waitUntil: 'networkidle' });
await page.waitForTimeout(1000);
await page.getByRole('tab', { name: 'List' }).click();
await page.waitForTimeout(600);
const row = page.getByRole('button', { name: /Python/ }).first();
await row.hover();
await page.waitForTimeout(300);
await page.screenshot({ path: `${out}/map-hover.png` });
await row.click();
await page.waitForTimeout(150);
await page.screenshot({ path: `${out}/map-expanding.png` });
await page.waitForTimeout(600);
await page.screenshot({ path: `${out}/map-open.png` });
await page.goto(base + '/unit/M00.U01', { waitUntil: 'networkidle' });
await page.waitForTimeout(900);
await page.getByRole('button', { name: 'Back' }).first().hover();
await page.waitForTimeout(300);
await page.screenshot({ path: `${out}/back-hover.png`, clip: { x: 0, y: 60, width: 500, height: 140 } });
await browser.close();
console.log(errors.length ? errors.join('\n') : 'ok');
