// Copies curriculum data from ../data into src/content and generates the
// static import index Metro needs for the v2 content (one file per module).
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve('..', 'data');
const out = path.resolve('src/content');
fs.mkdirSync(out, { recursive: true });

const legacyFiles = ['curriculum', 'first-28-days', 'resources', 'courses', 'books', 'papers', 'video-companions', 'study-guides'];
for (const name of legacyFiles) fs.copyFileSync(path.join(root, `${name}.json`), path.join(out, `${name}.json`));
console.log(`Bundled ${legacyFiles.length} legacy curriculum files.`);

// ---- Stable explicit topic IDs for the legacy curriculum -------------------
// IDs used to be derived from list position. They are now written once to
// topic-index.json and matched by (module, title) on every sync, so reordering
// or inserting topics in curriculum.json never changes an existing ID.
const indexFile = path.join(out, 'topic-index.json');
const previous = fs.existsSync(indexFile) ? JSON.parse(fs.readFileSync(indexFile, 'utf8')) : [];
// Duplicate titles inside one module are told apart by their occurrence number.
const keyOf = (list, i) => `${list[i].moduleId}|${list[i].title}|${list.slice(0, i).filter(t => t.moduleId === list[i].moduleId && t.title === list[i].title).length}`;
const byKey = new Map(previous.map((t, i) => [keyOf(previous, i), t.id]));
const used = new Set(previous.map(t => t.id));
const curriculum = JSON.parse(fs.readFileSync(path.join(out, 'curriculum.json'), 'utf8'));
const topics = [];
const seenTitles = new Map();
for (const m of curriculum.modules) {
  m.groups.forEach((g, gi) => {
    g.topics.forEach((title, ti) => {
      const nth = seenTitles.get(`${m.id}|${title}`) ?? 0;
      seenTitles.set(`${m.id}|${title}`, nth + 1);
      let id = byKey.get(`${m.id}|${title}|${nth}`);
      if (!id) {
        const positional = `${m.id}.${String(gi + 1).padStart(2, '0')}.${String(ti + 1).padStart(2, '0')}`;
        id = used.has(positional) ? `${m.id}.X${String(used.size + 1).padStart(4, '0')}` : positional;
      }
      used.add(id);
      topics.push({ id, moduleId: m.id, group: gi, title, ...(g.addedOn ? { added: true } : {}) });
    });
  });
}
fs.writeFileSync(indexFile, '[\n' + topics.map(t => ' ' + JSON.stringify(t)).join(',\n') + '\n]\n');
console.log(`Topic index: ${topics.length} explicit topic IDs.`);

// ---- v2 content -------------------------------------------------------------
const v2Source = path.join(root, 'v2');
const v2Out = path.join(out, 'v2');
const readJson = file => JSON.parse(fs.readFileSync(file, 'utf8'));
if (fs.existsSync(path.join(v2Source, 'modules'))) {
  fs.rmSync(v2Out, { recursive: true, force: true });
  fs.cpSync(v2Source, v2Out, { recursive: true });
  console.log('Copied data/v2/** into src/content/v2.');
} else {
  console.log('No data/v2/modules yet — keeping the bundled v2 fixture.');
}
fs.mkdirSync(path.join(v2Out, 'modules'), { recursive: true });

// Merge per-agent slices when the integrated files are missing.
const mergeSlices = (dir, target, combine, empty) => {
  const targetFile = path.join(v2Out, target);
  if (fs.existsSync(targetFile)) return;
  const sliceDir = path.join(v2Out, dir);
  let merged = empty;
  if (fs.existsSync(sliceDir)) {
    for (const f of fs.readdirSync(sliceDir).filter(f => f.endsWith('.json')).sort()) merged = combine(merged, readJson(path.join(sliceDir, f)));
  }
  fs.writeFileSync(targetFile, JSON.stringify(merged, null, 1) + '\n');
};
mergeSlices('resources', 'resources.json', (all, list) => {
  const seen = new Set(all.map(r => r.id));
  return [...all, ...(Array.isArray(list) ? list : []).filter(r => !seen.has(r.id) && seen.add(r.id))];
}, []);
mergeSlices('legacy', 'legacy-map.json', (all, map) => ({ ...all, ...map }), {});
for (const [name, empty] of [['tracks.json', []], ['weeks.json', []]]) {
  if (!fs.existsSync(path.join(v2Out, name))) fs.writeFileSync(path.join(v2Out, name), JSON.stringify(empty) + '\n');
}

const moduleFiles = fs.readdirSync(path.join(v2Out, 'modules')).filter(f => /^M\d+\.json$/.test(f)).sort();
for (const f of moduleFiles) readJson(path.join(v2Out, 'modules', f)); // fail fast on invalid JSON
const lines = [
  '// Generated by scripts/sync-content.mjs — do not edit by hand.',
  ...moduleFiles.map((f, i) => `import m${i} from './modules/${f}';`),
  "import tracks from './tracks.json';",
  "import weeks from './weeks.json';",
  "import resources from './resources.json';",
  "import legacyMap from './legacy-map.json';",
  `export const rawModules: unknown[] = [${moduleFiles.map((_, i) => `m${i}`).join(', ')}];`,
  'export const rawTracks: unknown = tracks;',
  'export const rawWeeks: unknown = weeks;',
  'export const rawResources: unknown = resources;',
  'export const rawLegacyMap: unknown = legacyMap;',
  '',
];
fs.writeFileSync(path.join(v2Out, 'index.ts'), lines.join('\n'));
console.log(`v2 index: ${moduleFiles.length} module file(s).`);
